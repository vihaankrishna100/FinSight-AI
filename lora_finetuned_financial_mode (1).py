base_model = AutoModelForCausalLM.from_pretrained("Qwen/Qwen2.5-7B-Instruct")
model = PeftModel.from_pretrained(base_model, "qwen2.5-7b-finance-lora")
merged_model = model.merge_and_unload()

# Save merged model
merged_model.save_pretrained("qwen2.5-7b-merged")

# Save tokenizer directly from the base model (not the adapter folder)
tokenizer = AutoTokenizer.from_pretrained("Qwen/Qwen2.5-7B-Instruct")
tokenizer.save_pretrained("qwen2.5-7b-merged")

