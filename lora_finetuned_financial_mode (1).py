from datasets import load_dataset
import torch
from transformers import AutoTokenizer, AutoModelForCausalLM, BitsAndBytesConfig
from peft import LoraConfig, get_peft_model, prepare_model_for_kbit_training
from trl import SFTTrainer, SFTConfig
import trl

print(f"TRL version: {trl.__version__}")

# Step 4: Load dataset
ds1 = load_dataset("bilalRahib/fiqa-personal-finance-dataset")

df = ds1["train"].map(lambda x: {
    "instruction": "Answer the following personal finance question.",
    "input": x["input"],
    "output": x["output"],
})

print(f"Total examples: {len(df)}")

# Step 5: Tokenizer

BASE_MODEL = "Qwen/Qwen2.5-7B-Instruct"

tokenizer = AutoTokenizer.from_pretrained(BASE_MODEL, use_fast=True)

tokenizer.pad_token = tokenizer.eos_token

tokenizer.padding_side = "right"

# Step 6: Format function

def format_example(x):
    return (
        f"### Instruction:\n{x['instruction']}\n\n"

        f"### Input:\n{x['input']}\n\n"

        f"### Response:\n{x['output']}"
    )

# Step 7: Check average sequence length

lengths = [len(tokenizer(format_example(x))["input_ids"]) for x in df.select(range(500))]
avg_len = sum(lengths) // len(lengths)

max_len = max(lengths)

print(f"Sequence lengths — avg: {avg_len}, max: {max_len}")

MAX_LEN = min(max_len, 512)
print(f"Using max_length: {MAX_LEN}")

# Step 8: 4-bit quantization config
bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_compute_dtype=torch.bfloat16,
    bnb_4bit_use_double_quant=True,
)

# Step 9: Load model
model = AutoModelForCausalLM.from_pretrained(

    BASE_MODEL,
    quantization_config=bnb_config,

    device_map="auto",
    attn_implementation="eager",
)

#  Step 10: Prepare for k-bit training
#k-bit training for 4-bit quantinization(best for 0-shot prompting)
model = prepare_model_for_kbit_training(model)

#  Step 11: LoRA config


#configures lora with r=8 meaning axr and bxr will have a value of 8 reducing parameters trained by almost 99%
lora_config = LoraConfig(

    r=8,
    lora_alpha=16,
    target_modules=["q_proj", "k_proj", "v_proj", "o_proj",
                    "gate_proj", "up_proj", "down_proj"],
    lora_dropout=0.05,
    bias="none",
    task_type="CAUSAL_LM",

)


model = get_peft_model(model, lora_config)
model.print_trainable_parameters()


trl_version = tuple(int(x) for x in trl.__version__.split(".")[:2])
max_len_kwarg = "max_length" if trl_version >= (0, 16) else "max_seq_length"

args = SFTConfig(
    output_dir="qwen2.5-7b-finance-lora",
    per_device_train_batch_size=4,
    gradient_accumulation_steps=4,
    num_train_epochs=1,
    learning_rate=2e-4,
    bf16=True,
    logging_steps=20,
    save_steps=200,
    save_total_limit=2,
    gradient_checkpointing=True,
    warmup_steps=100,
    lr_scheduler_type="cosine",
    #try lion and normal adam
    optim="paged_adamw_8bit",
    report_to="none",
    packing=True,
    **{max_len_kwarg: MAX_LEN},
)

# Step 13: Trainer
trainer_kwargs = dict(
    model=model,
    train_dataset=df,
    formatting_func=format_example,
    args=args,
)

if trl_version >= (0, 12):
    trainer_kwargs["processing_class"] = tokenizer
else:
    trainer_kwargs["tokenizer"] = tokenizer

trainer = SFTTrainer(**trainer_kwargs)

#  Step 14: Train


trainer.train()

#  Step 15: Save


trainer.save_model("qwen2.5-7b-finance-lora")
tokenizer.save_pretrained("qwen2.5-7b-finance-lora")
print("Training complete. Model saved to qwen2.5-7b-finance-lora/")

